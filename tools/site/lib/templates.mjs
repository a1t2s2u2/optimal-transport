// dist/ に出力する HTML（ランディング・各章・依存グラフ）を組み立てる。

import path from "node:path";
import { escapeHtml } from "./markdown.mjs";
import { BLOCK_TYPES } from "./blocks.mjs";
import { macrosToJsLiteral } from "./macros.mjs";

const FONTS_LINKS = `<link rel="preconnect" href="https://fonts.googleapis.com">
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
    <link href="https://fonts.googleapis.com/css2?family=Noto+Sans+JP:wght@400;700;900&family=Noto+Serif+JP:wght@400;700&display=swap" rel="stylesheet">`;

const GRAPH_ICON = `<svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round"><circle cx="6" cy="6" r="2.5"/><circle cx="18" cy="6" r="2.5"/><circle cx="6" cy="18" r="2.5"/><circle cx="18" cy="18" r="2.5"/><line x1="8.5" y1="6" x2="15.5" y2="6"/><line x1="6" y1="8.5" x2="6" y2="15.5"/><line x1="8" y1="8" x2="16" y2="16"/></svg>`;

// 各ページの dist 相対出力パス（本編→ main/、付録→ appendix/）。
export function outPathOf(section) {
  const sub = section.data.group === "appendix" ? "appendix" : "main";
  return `${sub}/${section.data.id}.html`;
}

// from ページ（dist 相対）から to リソース（dist 相対）への相対 URL。
export function relUrl(fromOutPath, toOutPath) {
  const rel = path.posix.relative(path.posix.dirname(fromOutPath), toOutPath);
  return rel || ".";
}

// <script> の中に埋めても壊れない JSON。
function safeJson(value) {
  return JSON.stringify(value).replace(/<\//g, "<\\/");
}

function mathJaxScript(macros) {
  return `<script>
      window.MathJax = {
        tex: {
          inlineMath: [["\\\\(", "\\\\)"]],
          displayMath: [["\\\\[", "\\\\]"]],
          macros: {
${macrosToJsLiteral(macros).replace(/<\//g, "<\\/")}
          }
        },
        svg: { fontCache: "global" }
      };
    </script>`;
}

function siteHeader(config, sections, currentSection) {
  const curOut = outPathOf(currentSection);
  const mainSecs = sections.filter((s) => s.data.group !== "appendix");
  const appendixSecs = sections.filter((s) => s.data.group === "appendix");

  const renderLink = (s, label) => {
    const cls = s.data.id === currentSection.data.id ? " is-current" : "";
    const href = relUrl(curOut, outPathOf(s));
    return `          <a href="${escapeHtml(href)}" class="site-header__link${cls}"><span class="site-header__num">${label}</span>${escapeHtml(s.data.nav ?? s.data.title)}</a>`;
  };

  const mainLinks = mainSecs.map((s, i) => renderLink(s, i + 1)).join("\n");
  const appendixNav = appendixSecs.length
    ? `\n          <span class="site-header__group-label">付録</span>\n${appendixSecs
        .map((s, i) => renderLink(s, String.fromCharCode(65 + i)))
        .join("\n")}`
    : "";

  return `<header class="site-header">
      <div class="site-header__inner">
        <a href="${escapeHtml(relUrl(curOut, "index.html"))}" class="site-header__home">
          <span class="site-header__logo">${escapeHtml(config.logo)}</span>
          <span class="site-header__name">${escapeHtml(config.title)}</span>
        </a>
        <nav class="site-header__nav">
${mainLinks}${appendixNav}
          <a href="${escapeHtml(relUrl(curOut, "graph.html"))}" class="site-header__link site-header__graph-link">${GRAPH_ICON}グラフ</a>
        </nav>
      </div>
    </header>`;
}

export function chapterTemplate(config, section, sections, index, blocks, macros) {
  const curOut = outPathOf(section);
  // 参照ジャンプ用に「現在ページからの相対 URL」で章ファイル表を作る（app.js が使用）。
  const chapterFilesMap = {};
  sections.forEach((s) => {
    chapterFilesMap[s.data.id] = relUrl(curOut, outPathOf(s));
  });

  const chapterNum = String(index + 1).padStart(2, "0");
  const eyebrow = section.data.eyebrow
    ? `<p class="chapter-hero__eyebrow">${escapeHtml(section.data.eyebrow)}</p>`
    : "";

  let pagerPrev = "<span></span>";
  let pagerNext = "<span></span>";
  if (index > 0) {
    const p = sections[index - 1];
    pagerPrev = `<a class="chapter-pager__link chapter-pager__prev" href="${escapeHtml(relUrl(curOut, outPathOf(p)))}">
          <span class="chapter-pager__dir">&larr; 前の章</span>
          <strong>${escapeHtml(p.data.title)}</strong>
        </a>`;
  }
  if (index < sections.length - 1) {
    const n = sections[index + 1];
    pagerNext = `<a class="chapter-pager__link chapter-pager__next" href="${escapeHtml(relUrl(curOut, outPathOf(n)))}">
          <span class="chapter-pager__dir">次の章 &rarr;</span>
          <strong>${escapeHtml(n.data.title)}</strong>
        </a>`;
  }

  const graphBase = relUrl(curOut, "graph.html");
  const blocksJson = safeJson(blocks).replaceAll("__GRAPH_BASE__", graphBase);

  return `<!doctype html>
<!-- Generated by tools/site — edit tex/ instead -->
<html lang="${escapeHtml(config.lang)}">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${escapeHtml(section.data.title)} — ${escapeHtml(config.title)}</title>
    ${FONTS_LINKS}
    <link rel="stylesheet" href="${relUrl(curOut, "styles.css")}" />
    ${mathJaxScript(macros)}
    <script defer src="https://cdn.jsdelivr.net/npm/mathjax@3/es5/tex-svg.js"></script>
    <script defer src="https://cdn.jsdelivr.net/npm/mermaid@10/dist/mermaid.min.js"></script>
    <script>
      window.__blocks = ${blocksJson};
      window.__chapterFiles = ${safeJson(chapterFilesMap)};
      window.__currentChapter = "${escapeHtml(section.data.id)}";
      window.__glossary = ${safeJson(config.glossary)};
      window.__features = ${safeJson(config.features)};
      window.__typeLabels = ${safeJson(typeLabels())};
      window.__typeColors = ${safeJson(typeColors())};
    </script>
    <script defer src="${relUrl(curOut, "app.js")}"></script>
    <noscript>
      <!-- ブロックの初期状態は透明で、app.js が可視化する。JS 無効時に本文が消えないようにする。 -->
      <style>.block, .example-band, .margin-note { opacity: 1 !important; transform: none !important; }</style>
    </noscript>
  </head>
  <body>
    <div class="reading-progress" aria-hidden="true">
      <div class="reading-progress__fill"></div>
    </div>

    ${siteHeader(config, sections, section)}

    <div class="page-layout">
      <nav class="chapter-toc" aria-label="目次"></nav>

      <main class="content">
        <div class="chapter-hero">
          <span class="chapter-hero__num" aria-hidden="true">${chapterNum}</span>
          <div class="chapter-hero__text">
            ${eyebrow}
            <h1 class="chapter-hero__title">${escapeHtml(section.data.title)}</h1>
          </div>
        </div>

        <article class="prose" id="${escapeHtml(section.data.id)}">
          ${section.html.replaceAll("__GRAPH_BASE__", graphBase)}
        </article>

        <nav class="chapter-pager">
          ${pagerPrev}
          ${pagerNext}
        </nav>
      </main>

      <aside class="ref-sidebar" aria-label="参照">
        <div class="ref-sidebar__header">
          <span class="ref-sidebar__label">参照</span>
        </div>
        <div class="ref-sidebar__body">
          <p class="ref-sidebar__empty">参照リンクをクリックすると<br>ここに定義や定理が表示されます</p>
        </div>
      </aside>
    </div>

    <dialog class="ref-sheet" id="ref-sheet">
      <div class="ref-sheet__content"></div>
      <button class="ref-sheet__close" type="button" aria-label="閉じる">&times;</button>
    </dialog>
  </body>
</html>
`;
}

// 章カードに出す「N 定義・M 定理」。features.chapterStats が false なら空。
function chapterBlockStats(blocks, chapterId) {
  const counts = {};
  for (const b of blocks) {
    if (b.chapter !== chapterId) continue;
    counts[b.type] = (counts[b.type] || 0) + 1;
  }
  const parts = [];
  for (const [type, meta] of Object.entries(BLOCK_TYPES)) {
    if (counts[type]) parts.push(`${counts[type]} ${meta.label}`);
  }
  return parts.join("・");
}

